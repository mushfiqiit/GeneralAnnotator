package generalannotator.inference;

/**
 * Renders {@code run_inference.sbatch}: a Slurm array job with one task per assignment group. Each
 * task loads the configured modules, activates the conda environment, sets offline Hugging Face
 * variables and runs the worker for its task. The script refuses to run outside {@code sbatch} or
 * from a directory that is not this submission. All interpolated values were validated by {@link
 * InferenceSettings} to contain only safe characters.
 */
public final class SlurmScript {

    public static final String FILE_NAME = "run_inference.sbatch";

    private SlurmScript() {}

    public static String render(InferenceSettings s, String submissionId, String runId, int taskCount) {
        StringBuilder b = new StringBuilder();
        b.append("#!/bin/bash -l\n");
        b.append("#SBATCH --job-name=").append(s.jobName()).append('\n');
        b.append("#SBATCH --account=").append(s.account()).append('\n');
        b.append("#SBATCH --partition=").append(s.partition()).append('\n');
        b.append("#SBATCH --qos=").append(s.qos()).append('\n');
        b.append("#SBATCH --time=").append(s.time()).append('\n');
        b.append("#SBATCH --ntasks=1\n");
        b.append("#SBATCH --cpus-per-task=").append(s.cpusPerTask()).append('\n');
        b.append("#SBATCH --gres=").append(s.gres()).append('\n');
        s.constraint().ifPresent(c -> b.append("#SBATCH --constraint=").append(c).append('\n'));
        s.memory().ifPresent(m -> b.append("#SBATCH --mem=").append(m).append('\n'));
        if (s.signalSeconds() > 0) {
            b.append("#SBATCH --signal=B:TERM@").append(s.signalSeconds()).append('\n');
        }
        b.append("#SBATCH --array=0-").append(taskCount - 1).append('%').append(s.arrayConcurrency()).append('\n');
        b.append("#SBATCH --output=logs/%x.%A_%a.out\n");
        b.append("#SBATCH --error=logs/%x.%A_%a.err\n");
        b.append("""
                #
                # Generated by GeneralAnnotator prepare-inference for submission %1$s (run %2$s).
                # Submit from this submission directory on the cluster:   sbatch %3$s
                # Each array task gets its own GPU, starts its own vLLM server on localhost with cached
                # weights (offline), runs its assigned prompts one request at a time (submission.json),
                # writes results/<warningId>/ and results/tasks/, and stops its server on exit.

                set -o pipefail   # no -u: conda activation scripts reference unset variables

                SUBMISSION_ID='%1$s'
                if [[ -z "${SLURM_ARRAY_TASK_ID:-}" ]]; then
                    echo "ERROR: submit this script with sbatch; it is a Slurm array job." >&2
                    exit 2
                fi
                cd "$SLURM_SUBMIT_DIR" || exit 2
                if ! grep -q "\\"submissionId\\": \\"$SUBMISSION_ID\\"" submission.json 2>/dev/null; then
                    echo "ERROR: submit from the directory of submission $SUBMISSION_ID (submission.json missing or different)." >&2
                    exit 2
                fi

                module purge > /dev/null 2>&1
                """.formatted(submissionId, runId, FILE_NAME));
        for (String module : s.modules()) {
            b.append("module load ").append(module).append(" || exit 2\n");
        }
        b.append("""
                eval "$(conda shell.bash hook)"
                conda activate '%1$s' || exit 2
                export HF_HOME='%2$s' HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 PYTHONUNBUFFERED=1

                echo "Submission $SUBMISSION_ID: array job ${SLURM_ARRAY_JOB_ID:-?}, task $SLURM_ARRAY_TASK_ID on $(hostname)"
                exec python3 worker/ga_inference_worker.py --submission "$PWD" --task "$SLURM_ARRAY_TASK_ID"
                """.formatted(s.condaEnv(), s.hfHome()));
        return b.toString();
    }
}
