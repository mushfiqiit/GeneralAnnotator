/**
 * Runs NullAway from a local checkout on an isolated working copy.
 *
 * <p>Invocation (see project-spec §6, "NullAway invocation"):
 *
 * <ol>
 *   <li><b>Setup.</b> In the checkout, run its Gradle wrapper with an external init script that
 *       builds {@code :nullaway:jar} from the current sources and writes the Error Prone processor
 *       path (Error Prone from the checkout's own dependency configuration, the built NullAway jar,
 *       NullAway's runtime dependencies).
 *   <li><b>Analysis.</b> Run {@code javac} from the configured JDK with {@code -Xplugin:ErrorProne},
 *       all other Error Prone checks disabled, NullAway at ERROR, and {@code AnnotatedPackages}
 *       set. All target sources under the configured roots are compiled in one invocation together
 *       with a generated probe file outside the target that contains one known NullAway violation.
 *   <li><b>Classification.</b> {@link NullAwayResultClassifier}.
 * </ol>
 *
 * The target's own build is not used. Generated files (init script, argument file, probe) live in
 * the run directory; compiled classes go to the run directory, not the working copy.
 */
public final class NullAwayChecker implements Checker {

    public static final String ID = "nullaway";

    /** Optional comma-separated NullAway {@code AnnotatedPackages} override. */
    public static final String ANNOTATED_PACKAGES_ENV = "GA_NULLAWAY_ANNOTATED_PACKAGES";

    static final String PROBE_PACKAGE = "generalannotator_probe";
    static final String PROBE_SOURCE = """
            package generalannotator_probe;

            /** Generated by GeneralAnnotator to prove that NullAway is active in this javac run. */
            final class GeneralAnnotatorProbe {
                static int probe() {
                    Object o = null;
                    return o.hashCode();
                }
            }
            """;

    /** javac launcher options Error Prone needs on JDK 16+ (cannot go in an argument file). */
    static final List<String> JVM_EXPORTS = List.of(
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.api=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.file=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.main=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.model=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.parser=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.processing=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.tree=ALL-UNNAMED",
            "-J--add-exports=jdk.compiler/com.sun.tools.javac.util=ALL-UNNAMED",
            "-J--add-opens=jdk.compiler/com.sun.tools.javac.code=ALL-UNNAMED",
            "-J--add-opens=jdk.compiler/com.sun.tools.javac.comp=ALL-UNNAMED");

    private final Path checkout;
    private final Optional<List<String>> configuredPackages;
    private final CommandRunner runner;

    private NullAwayChecker(Path checkout, Optional<List<String>> configuredPackages, CommandRunner runner) {
        this.checkout = checkout;
        this.configuredPackages = configuredPackages;
        this.runner = runner;
    }

    /**
     * Validates the checkout layout and NullAway-specific environment variables.
     *
     * @param checkout the {@code GA_CHECKER_HOME} directory
     */
    public static NullAwayChecker create(Path checkout, Map<String, String> env, CommandRunner runner)
            throws ConfigurationException {
        List<String> problems = new ArrayList<>();
        if (!Files.isExecutable(checkout.resolve("gradlew"))) {
            problems.add("GA_CHECKER_HOME=" + checkout + " has no executable gradlew; expected a NullAway "
                    + "source checkout (https://github.com/uber/NullAway).");
        }
        if (!Files.isRegularFile(checkout.resolve("nullaway").resolve("build.gradle"))) {
            problems.add("GA_CHECKER_HOME=" + checkout + " has no nullaway/build.gradle; expected a NullAway "
                    + "source checkout.");
        }
        Optional<List<String>> packages = Optional.empty();
        String value = env.get(ANNOTATED_PACKAGES_ENV);
        if (value != null) {
            try {
                packages = Optional.of(AnnotatedPackages.parseConfigured(value));
            } catch (IllegalArgumentException e) {
                problems.add(ANNOTATED_PACKAGES_ENV + "='" + value + "': " + e.getMessage());
            }
        }
        if (!problems.isEmpty()) {
            throw new ConfigurationException(problems);
        }
        return new NullAwayChecker(checkout, packages, runner);
    }

    @Override
    public String id() {
        return ID;
    }

    @Override
    public CheckerRun analyze(AnalysisRequest request) {
        try {
            return new Run(request).execute();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** State for one analysis. */
    private final class Run {
        final AnalysisRequest request;
        final List<RecordedCommand> commands = new ArrayList<>();
        final Map<String, Object> details = new LinkedHashMap<>();
        final List<String> roots;

        Run(AnalysisRequest request) {
            this.request = request;
            this.roots = request.sourceRoots().stream().map(Path::toString).toList();
            details.put("nullawayCheckout", checkout.toString());
        }

        CheckerRun execute() throws IOException {
            // 1. Sources and scope (cheap checks first).
            List<Path> sources = new ArrayList<>();
            for (Path root : request.sourceRoots()) {
                Path dir = request.workingCopyRoot().resolve(root);
                if (!Files.isDirectory(dir)) {
                    return failure(FailureKind.SETUP_FAILED, "source root '" + root
                            + "' is missing from the isolated copy (is it ignored by git?)");
                }
                try (Stream<Path> files = Files.walk(dir)) {
                    files.filter(p -> p.getFileName().toString().endsWith(".java"))
                            .filter(Files::isRegularFile)
                            .sorted()
                            .forEach(sources::add);
                }
            }
            if (sources.isEmpty()) {
                return failure(FailureKind.NO_SOURCES, "no .java files under source roots " + roots);
            }
            Set<String> declaredPackages = new LinkedHashSet<>();
            int unnamedPackageFiles = 0;
            for (Path source : sources) {
                // Lenient decoding: malformed bytes must not abort package detection.
                Optional<String> pkg = AnnotatedPackages.packageOf(
                        new String(Files.readAllBytes(source), StandardCharsets.UTF_8));
                if (pkg.isPresent()) {
                    declaredPackages.add(pkg.get());
                } else {
                    unnamedPackageFiles++;
                }
            }
            List<String> annotated = configuredPackages.orElseGet(
                    () -> AnnotatedPackages.minimalPrefixes(declaredPackages));
            details.put("annotatedPackages", annotated);
            details.put("annotatedPackagesSource",
                    configuredPackages.isPresent() ? ANNOTATED_PACKAGES_ENV : "derived from package declarations");
            if (annotated.isEmpty()) {
                return failure(FailureKind.SETUP_FAILED, "no named packages found under " + roots
                        + "; NullAway needs AnnotatedPackages (set " + ANNOTATED_PACKAGES_ENV + ")");
            }

            // 2. Build NullAway from the checkout and resolve the processor path.
            Path generated = request.generatedDirectory();
            Files.createDirectories(generated);
            Path initScript = generated.resolve("nullaway-processor-path.init.gradle");
            Files.writeString(initScript, resource("processor-path.init.gradle"), StandardCharsets.UTF_8);
            Path processorPathFile = generated.resolve("nullaway-processor-path.txt");
            Files.deleteIfExists(processorPathFile);
            CommandResult setup = runner.run(new CommandSpec(
                    List.of(checkout.resolve("gradlew").toString(), "--console=plain",
                            "--init-script", initScript.toString(),
                            ":nullaway:generalAnnotatorProcessorPath",
                            "-PgeneralAnnotator.output=" + processorPathFile),
                    checkout,
                    Map.of("JAVA_HOME", request.javaHome().toString()),
                    request.timeout()));
            commands.add(RecordedCommand.save(request.logsDirectory(), "nullaway-setup", setup));
            if (!setup.succeeded()) {
                return failure(setup.timedOut() ? FailureKind.TIMED_OUT : FailureKind.SETUP_FAILED,
                        "building NullAway in " + checkout + " failed (" + setup.describeStatus()
                                + "); see logs/nullaway-setup.stderr.txt" + lastLines(setup.stderr()));
            }
            if (!Files.isRegularFile(processorPathFile)) {
                return failure(FailureKind.SETUP_FAILED,
                        "NullAway setup succeeded but did not write " + processorPathFile);
            }
            ProcessorPath processorPath;
            try {
                processorPath = ProcessorPath.parse(Files.readString(processorPathFile), checkout);
            } catch (IllegalArgumentException e) {
                return failure(FailureKind.SETUP_FAILED, "invalid NullAway processor path: " + e.getMessage());
            }
            details.put("nullawayVersion", processorPath.nullawayVersion());
            details.put("nullawayJar", processorPath.nullawayJar().toString());
            details.put("errorProneCoreJar", processorPath.errorProneCoreJar().orElse(""));
            details.put("processorPath", processorPath.entries().stream().map(Path::toString).toList());

            // 3. Probe and javac invocation.
            Path probe = generated.resolve("probe").resolve(PROBE_PACKAGE).resolve("GeneralAnnotatorProbe.java");
            Files.createDirectories(probe.getParent());
            Files.writeString(probe, PROBE_SOURCE, StandardCharsets.UTF_8);
            details.put("probeFile", probe.toString());

            List<String> scope = new ArrayList<>(annotated);
            scope.add(PROBE_PACKAGE);
            Path classes = request.runDirectory().resolve("classes");
            Files.createDirectories(classes);
            List<String> args = new ArrayList<>(List.of(
                    "-XDcompilePolicy=simple",
                    "--should-stop=ifError=FLOW",
                    "-XDaddTypeAnnotationsToSymbol=true",
                    "-Xmaxerrs", "2147483647",
                    "-Xmaxwarns", "2147483647",
                    "-proc:none",
                    "-implicit:none",
                    "-d", classes.toString(),
                    "-sourcepath", "",
                    "-classpath", join(request.classpath()),
                    "-processorpath", join(processorPath.entries())));
            if (request.javacRelease().isPresent()) {
                args.addAll(List.of("--release", Integer.toString(request.javacRelease().getAsInt())));
            }
            args.add("-Xplugin:ErrorProne -XepDisableAllChecks -Xep:NullAway:ERROR"
                    + " -XepOpt:NullAway:AnnotatedPackages=" + String.join(",", scope));
            args.add(probe.toString());
            sources.forEach(s -> args.add(s.toString()));
            Path argFile = generated.resolve("javac.args");
            JavacArgFile.write(argFile, args);
            details.put("javacArgFile", argFile.toString());

            List<String> command = new ArrayList<>();
            command.add(request.javaHome().resolve("bin").resolve("javac").toString());
            command.addAll(JVM_EXPORTS);
            command.add("@" + argFile);
            CommandResult javac = runner.run(
                    new CommandSpec(command, request.workingCopyRoot(), Map.of(), request.timeout()));
            commands.add(RecordedCommand.save(request.logsDirectory(), "javac", javac));

            // 4. Classify.
            CompilerOutput output = JavacOutputParser.parse(javac.stderr(), javac.stdout());
            String probePath = probe.toString();
            NullAwayResultClassifier.Classification c =
                    NullAwayResultClassifier.classify(javac, output, probePath::equals);
            details.put("probeFindings", c.probeFindings().size());
            details.put("checkerActive", !c.probeFindings().isEmpty());
            details.put("javacReportedErrorCount",
                    output.reportedErrorCount().isPresent() ? output.reportedErrorCount().getAsInt() : null);
            details.put("javacReportedWarningCount",
                    output.reportedWarningCount().isPresent() ? output.reportedWarningCount().getAsInt() : null);
            details.put("generalMessages", output.generalMessages().stream()
                    .map(m -> m.severity().label() + ": " + m.text()).toList());
            details.put("unrecognizedOutputLines", output.unrecognizedLines());
            details.put("outputProblems", output.problems());

            Coverage coverage = coverage(sources.size(), annotated, unnamedPackageFiles, c.outcome());
            return new CheckerRun(ID, commands, c.outcome(), coverage, details);
        }

        private Coverage coverage(int sourceCount, List<String> annotated, int unnamedPackageFiles,
                CheckerOutcome outcome) throws IOException {
            List<String> limitations = new ArrayList<>();
            if (outcome instanceof ExecutionFailure f) {
                limitations.add("Analysis did not complete (" + f.kind() + "); the findings listed are only "
                        + "those observed before the failure and are not the full warning set.");
            }
            limitations.add("Only the configured source roots were analyzed: " + roots + ".");
            SortedCounts outside = javaFilesOutside();
            if (!outside.counts.isEmpty()) {
                limitations.add(outside.total + " Java file(s) elsewhere in the target were not analyzed "
                        + "(tests, other modules, samples); see javaFilesOutsideSourceRoots.");
            }
            limitations.add("NullAway checks only code in AnnotatedPackages " + annotated
                    + "; code outside them is treated as unannotated.");
            if (unnamedPackageFiles > 0) {
                limitations.add(unnamedPackageFiles + " analyzed file(s) are in the unnamed package, which "
                        + "AnnotatedPackages cannot cover, so NullAway treats them as unannotated.");
            }
            limitations.add("The target's own build was not run: its annotation processors (-proc:none), "
                    + "generated sources and build-specific compiler options are not applied.");
            if (request.javacRelease().isEmpty()) {
                limitations.add("No --release was set (GA_JAVAC_RELEASE); sources were compiled at the "
                        + "checker JDK's default language level and against its JDK API.");
            }
            return new Coverage(roots, sourceCount, outside.counts, limitations);
        }

        private record SortedCounts(TreeMap<String, Integer> counts, int total) {}

        private SortedCounts javaFilesOutside() throws IOException {
            Path root = request.workingCopyRoot();
            List<Path> analyzedRoots = request.sourceRoots().stream().map(root::resolve).toList();
            TreeMap<String, Integer> counts = new TreeMap<>();
            int total = 0;
            try (Stream<Path> files = Files.walk(root)) {
                for (Path p : files.filter(f -> f.getFileName().toString().endsWith(".java")).toList()) {
                    if (analyzedRoots.stream().noneMatch(p::startsWith)) {
                        Path rel = root.relativize(p);
                        String top = rel.getNameCount() > 1 ? rel.getName(0).toString() : ".";
                        counts.merge(top, 1, Integer::sum);
                        total++;
                    }
                }
            }
            return new SortedCounts(counts, total);
        }

        private CheckerRun failure(FailureKind kind, String reason) {
            return new CheckerRun(ID, commands, ExecutionFailure.before(kind, reason),
                    Coverage.none(roots, "Nothing was analyzed: " + reason), details);
        }
    }

    private static String join(List<Path> paths) {
        return paths.stream().map(Path::toString).collect(Collectors.joining(File.pathSeparator));
    }

    private static String lastLines(String text) {
        List<String> lines = text.lines().filter(l -> !l.isBlank()).toList();
        if (lines.isEmpty()) {
            return "";
        }
        return "\n" + String.join("\n", lines.subList(Math.max(0, lines.size() - 15), lines.size()));
    }

    private static String resource(String name) throws IOException {
        try (InputStream in = NullAwayChecker.class.getResourceAsStream(name)) {
            if (in == null) {
                throw new IOException("missing resource " + name);
            }
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }
}
