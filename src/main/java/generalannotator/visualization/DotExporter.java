package generalannotator.visualization;

import generalannotator.diagnostics.Diagnostic;
import generalannotator.graph.AnnotationNode;
import generalannotator.graph.GraphEdge;
import generalannotator.graph.GraphNode;
import generalannotator.graph.WarningGraph;
import generalannotator.graph.WarningNode;
import java.util.List;

/**
 * Exports a {@link WarningGraph} to Graphviz DOT. The graph model is not changed and knows nothing
 * about visualization.
 *
 * <ul>
 *   <li>Every node is drawn, including isolated ones; each is labeled with its existing ID only.
 *   <li>The node's source location, severity, checker and full message become an SVG hover tooltip.
 *   <li>Only edges present in the graph are drawn; none are invented (not even invisible layout
 *       edges). A graph without edges (every current graph) uses Graphviz's {@code osage} layout,
 *       selected by the {@code layout} graph attribute and still run by the {@code dot}
 *       executable. Its nodes are packed into a near-square grid in ID order ({@code
 *       packmode="array_u"} with {@code sortv}). The {@code dot} layout itself puts disconnected
 *       nodes in one wide row, and its component packing ignores {@code sortv} and swaps the first
 *       and last component (observed with Graphviz 12.1). Graphs with edges use the hierarchical
 *       {@code dot} layout, with packing.
 *   <li>An empty graph is rendered as a clear "No warnings" message.
 *   <li>Evaluation graphs: warning nodes are rounded boxes; warnings of a result state (introduced
 *       by a package) have a thicker solid border. Annotation nodes (one per annotation package) are ellipses filled by outcome (green
 *       completed, grey unevaluated or no-op, red failed or rejected, yellow ambiguous), labeled
 *       with their ID, outcome, number of edits and (when several answers share the package) number
 *       of answers, with every edit of the package (and its applier outcome), the counts and every
 *       originating answer in the tooltip.
 *       {@value GraphEdge#RESOLVED_BY} edges (warning → annotation) are green, {@value GraphEdge#INTRODUCES}
 *       edges (annotation → warning) red; both are solid, and there is no other edge kind or style. Nodes
 *       are labeled with their IDs (introduced warnings carry their round's IDs, {@code W1001, ...}); the
 *       tooltips name the round.
 *       Proposal associations are not drawn as edges.
 *   <li>Extended (multi-round) graphs are drawn the same way; an edge's provenance (evaluation, states,
 *       matcher, combined-result warning ID) is in its tooltip.
 * </ul>
 *
 * <p>Escaping (verified against Graphviz 12.1): inside double-quoted DOT strings, {@code "} becomes
 * {@code \"}, {@code &} becomes {@code &amp;} (Graphviz interprets HTML entities), and line breaks
 * become {@code \n}. Graphviz expands backslash escapes such as {@code \N} once in labels but twice in
 * tooltips, so a literal backslash is written as {@code \\} in labels and {@code \\\\} in tooltips.
 */
public final class DotExporter {

    private DotExporter() {}

    public static String toDot(WarningGraph graph) {
        StringBuilder out = new StringBuilder();
        out.append("// Generated by GeneralAnnotator from the warning graph of run ")
                .append(comment(graph.runId())).append(". Do not edit.\n");
        out.append("digraph \"warning_graph\" {\n");
        out.append("  graph [")
                .append(graph.edges().isEmpty() ? "layout=osage, " : "")
                .append("fontname=\"Helvetica\", labelloc=t, fontsize=14, pack=true, packmode=\"array_u\"")
                .append(", tooltip=").append(tooltip("Warning graph of run " + graph.runId()))
                .append(", label=").append(label(title(graph))).append("];\n");
        out.append("  node [shape=box, style=\"rounded,filled\", fontname=\"Helvetica\", fontsize=11, penwidth=1];\n");
        out.append("  edge [fontname=\"Helvetica\", fontsize=9];\n");

        List<GraphNode> nodes = graph.nodes();
        for (int i = 0; i < nodes.size(); i++) {
            GraphNode node = nodes.get(i);
            switch (node) {
                case WarningNode w -> out.append("  ").append(id(w.id()))
                        .append(" [id=").append(id(w.id()))
                        .append(", label=").append(label(w.id()))
                        .append(", tooltip=").append(tooltip(tooltipText(w)))
                        .append(", fillcolor=\"").append(fill(w)).append('"')
                        .append(w.root() ? "" : ", penwidth=2")
                        .append(", sortv=").append(i + 1)
                        .append("];\n");
                case AnnotationNode a -> out.append("  ").append(id(a.id()))
                        .append(" [id=").append(id(a.id()))
                        .append(", shape=ellipse, style=filled")
                        .append(", label=").append(label(a.id() + "\n" + a.outcome() + "\n" + a.edits().size()
                                + (a.edits().size() == 1 ? " edit" : " edits")
                                + (a.proposals().size() > 1 ? "\n" + a.proposals().size() + " answers" : "")))
                        .append(", tooltip=").append(tooltip(tooltipText(a)))
                        .append(", fillcolor=\"").append(fill(a)).append('"')
                        .append(", sortv=").append(i + 1)
                        .append("];\n");
            }
        }
        for (GraphEdge e : graph.edges()) {
            String color = switch (e.kind()) {
                case GraphEdge.RESOLVED_BY -> ", color=\"#2e7d32\", fontcolor=\"#2e7d32\"";
                case GraphEdge.INTRODUCES -> ", color=\"#c62828\", fontcolor=\"#c62828\"";
                default -> "";
            };
            out.append("  ").append(id(e.source())).append(" -> ").append(id(e.target()))
                    .append(" [label=").append(label(e.kind())).append(color)
                    .append(", tooltip=").append(tooltip(edgeTooltip(e)))
                    .append("];\n");
        }
        out.append("}\n");
        return out.toString();
    }

    static String edgeTooltip(GraphEdge e) {
        StringBuilder text = new StringBuilder(e.source() + " -> " + e.target() + " (" + e.kind() + ")");
        e.provenance().forEach((k, v) -> text.append('\n').append(k).append(": ").append(v));
        return text.toString();
    }

    static String title(WarningGraph graph) {
        if (graph.nodes().isEmpty()) {
            return "No warnings\nrun " + graph.runId() + " (" + graph.checkerId()
                    + "): the completed analysis reported no findings";
        }
        int warnings = graph.warningNodes().size();
        long annotations = graph.nodes().stream().filter(AnnotationNode.class::isInstance).count();
        long rounds = graph.nodes().stream().filter(AnnotationNode.class::isInstance)
                .map(n -> ((AnnotationNode) n).round()).filter(java.util.OptionalInt::isPresent).distinct().count();
        if (rounds > 1) {
            return "Extended evaluation graph: run " + graph.runId() + " (" + graph.checkerId() + ")\n"
                    + warnings + " warning node(s), " + annotations + " annotation node(s) in " + rounds
                    + " rounds, " + graph.edges().size() + " edge(s) - each package was evaluated alone against its "
                    + "source state; hover for details and provenance";
        }
        if (annotations > 0) {
            return "Evaluation graph: run " + graph.runId() + " (" + graph.checkerId() + ")\n"
                    + warnings + " warning node(s), " + annotations + " annotation node(s), " + graph.edges().size()
                    + " edge(s) - each annotation package was applied as a whole and evaluated alone against the "
                    + "baseline; hover for details";
        }
        return "Warning graph: run " + graph.runId() + " (" + graph.checkerId() + ")\n"
                + warnings + " warning node(s), " + graph.edges().size() + " edge(s)"
                + " - hover over a node for its location and message";
    }

    /** Tooltip text of an annotation node: edit, states, outcome, counts and proposal associations. */
    public static String tooltipText(AnnotationNode node) {
        StringBuilder text = new StringBuilder(node.id()).append(": ").append(node.canonical()).append('\n');
        for (AnnotationNode.PackageEdit e : node.edits()) {
            text.append("  ").append(e.canonical());
            e.applierOutcome().ifPresent(o -> text.append(" [").append(o).append(']'));
            text.append('\n');
        }
        node.round().ifPresent(r -> text.append("round ").append(r).append(", "));
        text.append("applied to ").append(node.baselineState());
        node.resultState().ifPresent(s -> text.append(" -> ").append(s));
        text.append("\noutcome ").append(node.outcome()).append(": ").append(node.detail());
        node.counts().ifPresent(c -> text.append("\nfindings ").append(c.baselineFindings()).append(" -> ")
                .append(c.resultFindings()).append("; resolved ").append(c.resolved()).append(", introduced ")
                .append(c.introduced()).append(", persisting ").append(c.persisting()).append(", ambiguous ")
                .append(c.ambiguousBaseline()).append('/').append(c.ambiguousResult()));
        if (!node.proposals().isEmpty()) {
            text.append(node.proposals().size() == 1 ? "\nproposed by the answer for " : "\nproposed by "
                    + node.proposals().size() + " answers, for ");
            text.append(String.join(", ", node.proposals().stream()
                    .map(p -> p.warningId() + " (" + p.group() + ")").toList()));
            text.append(" (associations, not resolutions)");
        }
        return text.toString();
    }

    private static String fill(AnnotationNode node) {
        return switch (node.outcome()) {
            case "COMPLETED" -> "#d4edda";
            case "AMBIGUOUS" -> "#fff3cd";
            case "UNEVALUATED", "NO_OP", "INTERRUPTED" -> "#e2e3e5";
            default -> "#f5c6cb";
        };
    }

    /** Tooltip text: ID, location, severity and checker, then the complete message. */
    public static String tooltipText(WarningNode node) {
        Diagnostic d = node.diagnostic();
        StringBuilder text = new StringBuilder(node.id());
        node.state().ifPresent(s -> text.append(" (state ").append(s)
                .append(node.round().isPresent() ? node.round().getAsInt() == 0 ? ", initial" : ", introduced in round "
                        + node.round().getAsInt() : "").append(')'));
        text.append('\n');
        text.append(node.targetPath().orElse(d.sourcePath())).append(':').append(d.line());
        if (d.column().isPresent()) {
            text.append(':').append(d.column().getAsInt());
        }
        text.append('\n').append(d.severity().label());
        d.checkerName().ifPresent(name -> text.append(" [").append(name).append(']'));
        text.append('\n').append(d.message());
        return text.toString();
    }

    private static String fill(WarningNode node) {
        return switch (node.diagnostic().severity()) {
            case ERROR -> "#f8d7da";
            case WARNING -> "#fff3cd";
            case NOTE -> "#e2e3e5";
        };
    }

    /** A quoted DOT identifier (node name); not subject to escape-sequence expansion. */
    static String id(String text) {
        return quote(text, "\\\\");
    }

    /** A quoted DOT label: backslash escapes are expanded once by Graphviz. */
    static String label(String text) {
        return quote(text, "\\\\");
    }

    /** A quoted DOT tooltip: backslash escapes are expanded twice by Graphviz. */
    static String tooltip(String text) {
        return quote(text, "\\\\\\\\");
    }

    private static String quote(String text, String literalBackslash) {
        StringBuilder out = new StringBuilder("\"");
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '\\' -> out.append(literalBackslash);
                case '"' -> out.append("\\\"");
                case '&' -> out.append("&amp;");
                case '\n' -> out.append("\\n");
                case '\r' -> { }
                case '\t' -> out.append(' ');
                default -> {
                    if (c >= 0x20) {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('"').toString();
    }

    private static String comment(String text) {
        return text.replaceAll("[\\r\\n]", " ");
    }
}
